-- Library Book Management System: schema (draft) + seed data
-- MySQL 8.0+ (CHECK constraints are enforced from 8.0.16)
DROP DATABASE IF EXISTS library;
CREATE DATABASE library;
USE library;

CREATE TABLE subjects (
  subject_id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(60) NOT NULL UNIQUE
);
CREATE TABLE authors (
  author_id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  country VARCHAR(50)
);
CREATE TABLE books (
  book_id INT AUTO_INCREMENT PRIMARY KEY,
  isbn CHAR(13) NOT NULL UNIQUE,
  title VARCHAR(200) NOT NULL,
  author_id INT NOT NULL,
  subject_id INT NOT NULL,
  publication_year SMALLINT,
  total_copies INT NOT NULL,
  copies_available INT NOT NULL,
  FOREIGN KEY (author_id) REFERENCES authors(author_id),
  FOREIGN KEY (subject_id) REFERENCES subjects(subject_id),
  CONSTRAINT chk_total CHECK (total_copies >= 1),
  CONSTRAINT chk_available CHECK (copies_available >= 0 AND copies_available <= total_copies)
);
CREATE TABLE members (
  member_id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE,
  phone CHAR(10),
  join_date DATE NOT NULL,
  status ENUM('active','suspended') NOT NULL DEFAULT 'active'
);
CREATE TABLE issued_books (
  issue_id INT AUTO_INCREMENT PRIMARY KEY,
  book_id INT NOT NULL,
  member_id INT NOT NULL,
  issue_date DATE NOT NULL,
  due_date DATE NOT NULL,
  return_date DATE NULL,
  FOREIGN KEY (book_id) REFERENCES books(book_id),
  FOREIGN KEY (member_id) REFERENCES members(member_id),
  CONSTRAINT chk_due CHECK (due_date >= issue_date),
  CONSTRAINT chk_return CHECK (return_date IS NULL OR return_date >= issue_date)
);

